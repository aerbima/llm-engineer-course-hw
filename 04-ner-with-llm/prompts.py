"""Промпты: роль модели, что извлекать и в каком формате отвечать."""

SYSTEM_PROMPT = """Ты — строгий и точный AI-помощник опытного юриста.
Твоя задача — извлекать факты из текста юридического документа без искажений и выдумываний.
Строгие правила:
1. Бери данные ТОЛЬКО из текста. Ничего не додумывай и не вычисляй.
2. Если сведений нет в тексте — ставь null (для списка — пустой список []).
3. ИНН, КПП, суммы и даты переписывай символ в символ так, как они записаны в тексте.
4. Отвечай ТОЛЬКО валидным JSON-объектом. Без пояснений, без Markdown, без ```."""


# Пример (few-shot): короткий текст и правильный ответ на него в виде JSON. 
# Модель видит этот пример и понимает, что от неё требуется.
FEW_SHOT_TEXT = """ДОГОВОР НА ВЫПОЛНЕНИЯ ПРОЕКТНЫХ РАБОТ № 15/П
г. Минск, 11 ноября 1978 г.
ООО «АэрБИМ» (ИНН 1655001234, КПП 165501888), именуемое «Проектировщик», и
АО «АЙБИМ» (ИНН 7701987654, КПП 770101001), именуемое «Заказчик», заключили договор.
Цена договора — 480 000 (четыреста восемьдесят тысяч) рублей.
Проектировщик передаёт проект в течение 10 рабочих дней с даты оплаты.
Договор действует до 31.12.1978."""

FEW_SHOT_JSON = """{
  "document_type": "договор на выполнения проектных работ",
  "contract_number": "15/П",
  "parties": [
    {"role": "Проектировщик", "name": "ООО «АэрБИМ»", "inn": "1655001234", "kpp": "165501888"},
    {"role": "Заказчик", "name": "АО «АЙБИМ»", "inn": "7701987654", "kpp": "770101001"}
  ],
  "dates": {"signing_date": "11 ноября 1978 г.", "valid_from": null, "valid_until": "31.12.1978"},
  "amounts": [
    {"value": 480000, "currency": "RUB", "source_text": "480 000 (четыреста восемьдесят тысяч) рублей", "purpose": "цена договора"}
  ],
  "obligation_terms": [
    {"obligation": "передать проект", "term": "в течение 10 рабочих дней с даты оплаты", "deadline_date": null}
  ]
}"""

USER_PROMPT_TEMPLATE = """Извлеки из текста документа именованные сущности:
- document_type: вид документа (договор поставки, договор на выполнения проектных работ, NDA, доверенность, решение суда и т.п.)
- contract_number: номер договора/документа или null
- parties: стороны — role (роль в документе), name (название или ФИО), inn (ИНН), kpp (КПП); нет значения поля — null; если ничего нет — пустой список [], не null
- dates: signing_date (дата подписания), valid_from (начало действия), valid_until (окончание действия); нет значения — null
- amounts: суммы — value (число без пробелов), currency (код: RUB, USD, EUR, KZT, BYN), source_text (как в тексте), purpose (за что); нет значения поля — null; если ничего нет — пустой список [], не null
- obligation_terms: сроки обязательств — obligation (что сделать), term (срок как в тексте), deadline_date (конкретная дата или null); если ничего нет — пустой список [], не null

Пример.
Текст:
{few_shot_text}
Ответ:
{few_shot_json}

Теперь обработай настоящий документ. Верни только JSON той же структуры.
Текст:
{text}"""

def build_messages(text: str) -> list[dict]:
    """Собирает список сообщений для API: системное + пользовательское c few_shot_text и few_shot_json."""
    user_text = USER_PROMPT_TEMPLATE.format(
        few_shot_text=FEW_SHOT_TEXT,
        few_shot_json=FEW_SHOT_JSON,
        text=text,
    )
    return [
        {"role": "system", "text": SYSTEM_PROMPT},
        {"role": "user", "text": user_text},
    ]